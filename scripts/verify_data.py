"""Prove the data in this repo is the seeded, fictitious build and nothing else.

Usage:
  python -I scripts/verify_data.py                 # check data/ against data/MANIFEST.sha256
  python -I scripts/verify_data.py <rebuilt_dir>   # check a folder you rebuilt with build_data.py against the same manifest
  python -I scripts/verify_data.py --write         # (maintainers) rewrite the manifest after an intentional data change

data/MANIFEST.sha256 lists a SHA-256 hash for every file that scripts/build_data.py generates from the public
AdventureWorksDW sample (seed 20261111). If a rebuilt folder matches every hash, the committed data is exactly what the
seeded generator produces: no real company data was added or edited. fx/FX_Rates.csv is listed separately: it holds real,
public Bank of Canada exchange rates (not generated, not company data) and is checked for presence only.
"""
import hashlib, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, 'data', 'MANIFEST.sha256')
NOT_GENERATED = {'fx/FX_Rates.csv'}          # public Bank of Canada rates, fetched separately
SKIP = {'MANIFEST.sha256'}


def sha(path):
    with open(path, 'rb') as f:
        return hashlib.sha256(f.read().replace(b'\r\n', b'\n')).hexdigest()   # line-ending neutral (Windows checkouts)


def files(folder):
    out = []
    for d, _, fs in os.walk(folder):
        for f in fs:
            rel = os.path.relpath(os.path.join(d, f), folder).replace(os.sep, '/')
            if rel not in SKIP and not rel.startswith('.'):
                out.append(rel)
    return sorted(out)


def main():
    args = sys.argv[1:]
    data = os.path.join(ROOT, 'data')
    if args == ['--write']:
        with open(MANIFEST, 'w', encoding='utf-8', newline='\n') as f:
            f.write('# SHA-256 of every file generated by scripts/build_data.py (seed 20261111) from the public AdventureWorksDW sample.\n'
                    '# Check with: python -I scripts/verify_data.py [rebuilt_dir]\n')
            for rel in files(data):
                if rel not in NOT_GENERATED:
                    f.write(f'{sha(os.path.join(data, rel))}  {rel}\n')
        print(f'Manifest written: {MANIFEST}')
        return 0
    target = os.path.abspath(args[0]) if args else data
    expected = {}
    for line in open(MANIFEST, encoding='utf-8'):
        if line.strip() and not line.startswith('#'):
            h, rel = line.split(None, 1)
            expected[rel.strip()] = h
    found = set(files(target)) - NOT_GENERATED
    bad = [rel for rel, h in expected.items() if rel not in found or sha(os.path.join(target, rel)) != h]
    extra = sorted(found - set(expected))
    if not args:
        bad += [f'{rel} missing' for rel in NOT_GENERATED if not os.path.exists(os.path.join(data, rel))]
    if bad or extra:
        print('DATA CHECK FAILED')
        for x in bad:
            print('  differs or missing:', x)
        for x in extra:
            print('  not produced by the generator:', x)
        return 1
    print(f'Data check passed: {len(expected)} generated files match the seeded build byte for byte'
          + ('' if args else '; FX file present (public Bank of Canada rates)') + '.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
